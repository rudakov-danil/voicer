def shift(doc: str, day: date, week_no: int):
    """Окно приёма врача в этот день или None. Будни — утро 8–14 или вечер 13–19 (меняются по неделям),
    суббота — 9–14 через неделю, воскресенье — дежурные врачи 10–15."""
    wd = day.weekday()
    i = ORDER.index(doc)
    if wd == 6:
        return (10, 15) if (i + week_no) % 3 == 0 else None
    if wd == 5:
        return (9, 14) if (i + week_no) % 2 == 0 else None
    morning = (BASE_SHIFT[doc] == "m") ^ (week_no % 2 == 1)
    return (8, 14) if morning else (13, 19)


