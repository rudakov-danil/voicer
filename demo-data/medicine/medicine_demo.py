def chance(p: float) -> bool:
    return rnd.random() < max(0.0, min(1.0, p))


def years(n: int) -> str:
    m10, m100 = n % 10, n % 100
    return "год" if m10 == 1 and m100 != 11 else "года" if 2 <= m10 <= 4 and not 12 <= m100 <= 14 else "лет"


def days_word(n: int) -> str:
    m10, m100 = n % 10, n % 100
    return "день" if m10 == 1 and m100 != 11 else "дня" if 2 <= m10 <= 4 and not 12 <= m100 <= 14 else "дней"


