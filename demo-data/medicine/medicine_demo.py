def _until() -> time:
    for a in sys.argv[3:]:
        if a.startswith("--until="):
            hh, mm = a.split("=", 1)[1].split(":")
            return time(int(hh), int(mm))
    now = datetime.now(ALMATY)
    if now.date() == TODAY:
        cut = now - timedelta(minutes=5)
        return cut.time() if cut.date() == TODAY else time(0, 0)
    return time(12, 0)


