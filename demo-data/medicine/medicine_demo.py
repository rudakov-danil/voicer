def fill(text: str, ctx: dict) -> str:
    """{ж|м} — по полу пациента (у ребёнка — ребёнка), [мама|папа] — по сопровождающему, {name} — числа."""
    for k, v in ctx["nums"].items():
        text = text.replace("{" + k + "}", str(v))
    text = re.sub(r"\{([^{}|]*)\|([^{}|]*)\}", lambda m: m.group(1) if ctx["sex"] == "f" else m.group(2), text)
    return re.sub(r"\[([^\[\]|]*)\|([^\[\]|]*)\]", lambda m: m.group(1) if ctx.get("parent", "f") == "f" else m.group(2), text)


def kg(n: int) -> str:
    m10, m100 = n % 10, n % 100
    return "килограмм" if m10 == 1 and m100 != 11 else "килограмма" if 2 <= m10 <= 4 and not 12 <= m100 <= 14 else "килограммов"


