import { X } from 'lucide-react'

type Props = {
  onClose: () => void
  /** "editor" — справка по редактору скрипта; "rules" — про апсейл/кроссейл. */
  mode?: 'editor' | 'rules'
}

export function HelpModal({ onClose, mode = 'editor' }: Props) {
  return (
    <div className="modal-overlay" onClick={(e) => { if (e.target === e.currentTarget) onClose() }}>
      <div className="modal-card modal-card--wide" style={{ maxHeight: '88vh' }}>
        <div className="modal-header">
          <div className="modal-title">
            {mode === 'editor' ? 'Как составить скрипт продаж' : 'Апсейл и кросс-сейл: определения'}
          </div>
          <button className="btn-icon" onClick={onClose}><X size={16} /></button>
        </div>
        <div className="modal-body help-body">
          {mode === 'editor' ? <EditorHelp /> : <RulesHelp />}
        </div>
        <div className="modal-footer">
          <button className="btn btn-primary" onClick={onClose}>Понятно</button>
        </div>
      </div>
    </div>
  )
}

function EditorHelp() {
  return (
    <>
      <section>
        <h3>Что такое скрипт</h3>
        <p>Скрипт — это список этапов, которые продавец должен пройти в разговоре с клиентом.
          LLM прогоняет каждый звонок и оценивает, насколько этапы были выполнены. Результат идёт в
          аналитику и в персональные отчёты для руководства.</p>
      </section>

      <section>
        <h3>Поля скрипта</h3>
        <dl className="help-fields">
          <dt>Название</dt>
          <dd>Видят руководители в списке. Должно отражать сценарий — например, «Продажа холодильников, средний чек».</dd>
          <dt>Описание</dt>
          <dd>Текст для команды (НЕ попадает в промт LLM). Краткий контекст: когда применяется, для какой категории.</dd>
        </dl>
      </section>

      <section>
        <h3>Этапы</h3>
        <dl className="help-fields">
          <dt>Название этапа</dt>
          <dd>Короткое, по сути: «Выявление потребности», «Презентация продукта», «Закрытие сделки».</dd>
          <dt>Вес (%)</dt>
          <dd>Сколько этап весит в итоговом балле. Сумма весов всех этапов = 100%. Жмите «Нормализовать», если ошиблись.</dd>
          <dt>Обязательный</dt>
          <dd>Если включено и этап не выполнен — разговор считается слабым. Если выключено — этап засчитывается, но его пропуск не критичен.</dd>
          <dt>Описание этапа</dt>
          <dd><strong>Идёт в промт LLM</strong> — критично для точности. Опишите, что именно должен сделать продавец: «Уточнил, для кого покупка, какой бюджет, какие требования к функциям».</dd>
          <dt>Эталонные фразы</dt>
          <dd>Образцы идеального выполнения. LLM использует их как референс. Достаточно 2–4 примеров: «Для кого выбираете?», «Какой у вас бюджет?».</dd>
        </dl>
      </section>

      <section>
        <h3>Советы</h3>
        <ul>
          <li>5–8 этапов — оптимально. Меньше — поверхностно, больше — LLM начинает теряться.</li>
          <li>Сначала всегда «Установление контакта», в конце — «Закрытие сделки» / «Допродажа».</li>
          <li>Тестируйте на реальной записи (кнопка «Тест на записи») — увидите, как LLM оценит черновик, ничего не сохранится в базу.</li>
        </ul>
      </section>
    </>
  )
}

function RulesHelp() {
  return (
    <>
      <section>
        <h3>Апсейл (Up-sell)</h3>
        <p>Продажа более <strong>дорогой</strong> или продвинутой версии того же продукта.
          Цель — увеличить средний чек по основному товару.</p>
        <p className="help-example">
          <strong>Пример:</strong> клиент пришёл за iPhone 15 — продавец предлагает iPhone 15 Pro Max.
          Триггер-продукт: «iPhone 15», обязательное предложение: «iPhone 15 Pro / Pro Max».
        </p>
      </section>

      <section>
        <h3>Кросс-сейл (Cross-sell)</h3>
        <p>Предложение <strong>сопутствующих</strong> товаров к основной покупке.
          Цель — расширить чек.</p>
        <p className="help-example">
          <strong>Пример:</strong> клиент берёт ноутбук — продавец обязан предложить сумку, мышку и расширенную гарантию.
          Триггер-продукт: «Ноутбук», обязательные предложения: «Сумка», «Мышь», «Гарантия 2 года».
        </p>
      </section>

      <section>
        <h3>Как это работает</h3>
        <p>LLM проверяет каждый разговор: если продавец упомянул триггер-продукт, но не предложил
          указанные товары — разговор отмечается как пропущенный апсейл / кросс-сейл и попадает в отчёт
          о потерянной выручке.</p>
      </section>
    </>
  )
}
